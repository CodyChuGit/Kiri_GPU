#!/usr/bin/env bash
# The "raw" GPU path: hand a container the NVIDIA device nodes and the host's
# driver files with plain --device / --device-cgroup-rule / bind mounts, no
# CDI support in the engine. This is the route that works on upstream Kiri
# 0.2.x, where --gpus is refused. The Kiri_GPU fork's native CDI path
# (--gpus all, Compose device reservations) does not need any of this.
#
#   gpu-raw.sh args               one `docker run` argument per line
#   gpu-raw.sh compose <service>  a Compose override file for <service>
#   gpu-raw.sh list               what would be passed, human readable
#
# File list: the hostPath mounts in the CDI spec nvidia-ctk wrote
# (/var/run/cdi/nvidia.yaml, else /etc/cdi/nvidia.yaml), else the driver
# libraries ldconfig knows. Without the CDI hooks nothing creates the
# soname links (libcuda.so.1 -> libcuda.so.580.x) in the container, so every
# library is also bind-mounted under each name the host links to it by.
#
# Env: GPU_RAW_SPEC   spec file to read instead of the default search
#      GPU_RAW_GPUS   "all" (default) or a comma list of indexes, e.g. 0 or 0,1
set -euo pipefail

mode=${1:-list}
spec=${GPU_RAW_SPEC:-}
if [ -z "$spec" ]; then
  for f in /var/run/cdi/nvidia.yaml /etc/cdi/nvidia.yaml; do
    [ -r "$f" ] && { spec=$f; break; }
  done
fi
gpus=${GPU_RAW_GPUS:-all}

# --- device nodes -----------------------------------------------------------
devices=()
add_dev() { [ -c "$1" ] && devices+=("$1"); return 0; }
add_dev /dev/nvidiactl
add_dev /dev/nvidia-uvm
add_dev /dev/nvidia-uvm-tools
add_dev /dev/nvidia-modeset
if [ "$gpus" = all ]; then
  for d in /dev/nvidia[0-9]*; do add_dev "$d"; done
else
  IFS=, read -r -a idx <<<"$gpus"
  for i in "${idx[@]}"; do
    [ -c "/dev/nvidia$i" ] || { echo "gpu-raw: /dev/nvidia$i does not exist" >&2; exit 1; }
    add_dev "/dev/nvidia$i"
  done
fi
# nvidia-caps (MIG / fabric) nodes, when the driver made them.
for d in /dev/nvidia-caps/*; do add_dev "$d"; done

# Device cgroup rules by major number, so nodes a CUDA library opens later
# (e.g. a UVM tools node) are allowed too. 195 is the NVIDIA GPU major.
rules=("c 195:* rwm")
while read -r major name; do
  case $name in nvidia-uvm|nvidia-caps|nvidia-caps-imex-channels|nvidia-nvswitch|nvidia-nvlink) rules+=("c $major:* rwm") ;; esac
done < /proc/devices

# --- driver files -------------------------------------------------------------
# host<TAB>container pairs, de-duplicated.
declare -A seen=()
mounts=()
add_mount() { # host container
  local h=$1 c=${2:-$1}
  [ -e "$h" ] || return 0
  [ -c "$h" ] && return 0           # device nodes go through --device
  [ -n "${seen[$c]:-}" ] && return 0
  seen[$c]=1
  mounts+=("$h"$'\t'"$c")
}
# Every name the host links to a library by, in the same directory.
add_lib() { # host-path container-path
  local h=$1 c=${2:-$1} real dir base
  add_mount "$h" "$c"
  [ -f "$h" ] || return 0
  real=$(readlink -f "$h"); dir=$(dirname "$h"); base=$(basename "$real")
  # Links share the library's stem: libcuda.so, libcuda.so.1 -> libcuda.so.580.95.05
  for l in "$dir/${base%%.so*}".so*; do
    [ -L "$l" ] || continue
    [ "$(readlink -f "$l")" = "$real" ] || continue
    add_mount "$real" "$(dirname "$c")/$(basename "$l")"
  done
}

if [ -n "$spec" ]; then
  src="cdi:$spec"
  # nvidia-ctk writes:   - hostPath: X \n     containerPath: Y
  while IFS=$'\t' read -r h c; do
    case $h in
      *.so|*.so.*) add_lib "$h" "$c" ;;
      *) add_mount "$h" "$c" ;;
    esac
  done < <(awk '
    /^[[:space:]]*-?[[:space:]]*hostPath:/ { sub(/.*hostPath:[[:space:]]*/, ""); gsub(/"/, ""); h=$0; next }
    /^[[:space:]]*containerPath:/ && h != "" { sub(/.*containerPath:[[:space:]]*/, ""); gsub(/"/, ""); print h "\t" $0; h="" }
  ' "$spec")
else
  src="ldconfig"
  while read -r path; do add_lib "$path"; done < <(
    ldconfig -p | awk -F'=> ' '/(libcuda|libnvidia-|libnvcuvid|libnvoptix|libcudadebugger)[^ ]*\.so/ && /x86-64/ {print $2}' | sort -u)
  for b in nvidia-smi nvidia-debugdump nvidia-persistenced nvidia-cuda-mps-control nvidia-cuda-mps-server; do
    p=$(command -v "$b" 2>/dev/null) && add_mount "$p" "/usr/bin/$b"
  done
  add_mount /run/nvidia-persistenced/socket
  for f in /lib/firmware/nvidia/*/gsp_*.bin; do add_mount "$f"; done
fi

[ ${#devices[@]} -gt 0 ] || { echo "gpu-raw: no /dev/nvidia* nodes; is the driver loaded? (sudo nvidia-modprobe -u -c=0)" >&2; exit 1; }

case $mode in
  args)
    for d in "${devices[@]}"; do printf -- '--device=%s\n' "$d"; done
    for r in "${rules[@]}"; do printf -- '--device-cgroup-rule=%s\n' "$r"; done
    for m in "${mounts[@]}"; do printf -- '--volume=%s:%s:ro\n' "${m%%$'\t'*}" "${m#*$'\t'}"; done
    ;;
  compose)
    svc=${2:?usage: gpu-raw.sh compose <service>}
    echo "# Generated by gpu-raw.sh from $src on $(hostname) ($(date -u +%FT%TZ))."
    echo "# Regenerate after every NVIDIA driver update: the library names carry its version."
    echo "services:"
    echo "  $svc:"
    echo "    deploy: !reset {}   # drop the CDI reservation the base file asks for"
    echo "    devices:"
    for d in "${devices[@]}"; do echo "      - $d:$d:rwm"; done
    echo "    device_cgroup_rules:"
    for r in "${rules[@]}"; do echo "      - '$r'"; done
    echo "    volumes:"
    for m in "${mounts[@]}"; do
      echo "      - {type: bind, source: \"${m%%$'\t'*}\", target: \"${m#*$'\t'}\", read_only: true}"
    done
    ;;
  list)
    echo "source: $src"
    echo "devices (${#devices[@]}):"; printf '  %s\n' "${devices[@]}"
    echo "cgroup rules:"; printf '  %s\n' "${rules[@]}"
    echo "mounts (${#mounts[@]}):"
    for m in "${mounts[@]}"; do printf '  %s -> %s\n' "${m%%$'\t'*}" "${m#*$'\t'}"; done
    ;;
  *) echo "usage: gpu-raw.sh args | compose <service> | list" >&2; exit 2 ;;
esac
